from __future__ import annotations
import math
import random


def доли(*значения: float) -> None:
    if any(not math.isfinite(x) or not 0 <= x <= 1 for x in значения):
        raise ValueError("Ожидались конечные значения от 0 до 1")


def надёжность(поддержка: float, опровержение: float,
                исходное: float = .5, сила: float = 2.) -> float:
    доли(исходное)
    if (not all(math.isfinite(x) for x in (поддержка, опровержение, сила))
            or поддержка < 0 or опровержение < 0 or сила <= 0):
        raise ValueError("Неверные веса оснований")
    return (сила * исходное + поддержка) / (сила + поддержка + опровержение)


def забота(старая: float, пластичность: float, качество: float,
           доза: float, сближение: float, разрыв: float) -> float:
    доли(старая, пластичность, качество, доза, сближение, разрыв)
    плюс = .03 * пластичность * качество * доза * сближение
    минус = .006 * пластичность * качество * доза * разрыв
    сумма = плюс + минус
    if сумма == 0:
        return старая
    return старая + (-math.expm1(-сумма)) * (плюс / сумма - старая)


def сопротивление(принятие: float, уверенность: float,
                    тяжесть: float, исключение: float = 0.) -> float:
    доли(принятие, уверенность, тяжесть, исключение)
    return принятие * уверенность * тяжесть * (1 - исключение)


def объединение(записи: list[tuple[str, float]]) -> float:
    группы: dict[str, float] = {}
    for ключ, величина in записи:
        доли(величина)
        группы[ключ] = max(группы.get(ключ, 0.), величина)
    return min(1., sum(группы.values()))


def принятие_нормы(старое: float, цель: float, пластичность: float,
                    качество: float, доза: float) -> float:
    доли(старое, цель, пластичность, качество, доза)
    альфа = -math.expm1(-.02 * пластичность * качество * доза)
    return старое + альфа * (цель - старое)


def скорость_признаков(канал: float, наблюдательность: float,
                        внимание: float, сознание: bool = True,
                        доступность: bool = True) -> float:
    доли(канал, наблюдательность, внимание)
    if not сознание or not доступность:
        return 0.
    return 4 * канал * (.25 + .75 * наблюдательность) * (.25 + .75 * внимание)


def проверки() -> list[str]:
    выполнено: list[str] = []

    def проверить(имя: str, условие: bool) -> None:
        if not условие:
            raise AssertionError(имя)
        выполнено.append(имя)

    def близко(имя: str, значение: float, ожидается: float) -> None:
        проверить(имя, math.isclose(значение, ожидается, rel_tol=1e-12, abs_tol=1e-12))

    близко("Нейтральное исходное ожидание", надёжность(0, 0), .5)
    близко("Семь исполнений из восьми", надёжность(7, 1), .8)
    близко("Четыре возврата из четырёх", надёжность(4, 0), 5/6)
    проверить("Конечный опыт не гарантирует успех", надёжность(1000, 0) < 1)
    проверить("Разные тематические основания дают разные ожидания", надёжность(7, 1) > надёжность(1, 7))
    близко("Смесь оценки сообщения", .9*.8+(1-.9)*.2, .74)
    близко("Качество контакта", .8*.9*(1-.1), .648)
    близко("Один эпизод сближения", забота(.2, .5, 1, 1, .8, 0), .2095426297104556)
    сила = .2
    for _ in range(20):
        сила = забота(сила, .5, 1, 1, .8, 0)
    близко("Двадцать независимых эпизодов", сила, .3706977111467572)
    близко("Нет пластичности", забота(.2, 0, 1, 1, 1, 1), .2)
    близко("Нет воспринятого эпизода", забота(.2, .5, 0, 1, 1, 1), .2)
    близко("Нулевая доза", забота(.2, .5, 1, 0, 1, 1), .2)
    близко("Нет основания для изменения связи", забота(.2, .5, 1, 1, 0, 0), .2)
    проверить("Разрыв может ослабить связь", забота(.8, .5, 1, 1, 0, 1) < .8)
    близко("Расчёт сопротивления", сопротивление(.9, .8, .7), .504)
    близко("Непринятая норма", сопротивление(0, .8, .7), 0)
    близко("Полное известное исключение", сопротивление(.9, .8, .7, 1), 0)
    близко("Синонимы не суммируются", объединение([("ложь", .504), ("ложь", .45)]), .504)
    близко("Независимые аспекты", объединение([("ложь", .504), ("ложь", .45), ("приватность", .18)]), .684)
    близко("Ограничение общей моральной цены", объединение([("а", .8), ("б", .8)]), 1)
    близко("Нет рассмотренных норм", объединение([]), 0)
    близко("Условные вероятности санкции", .4*.8*.5*.6, .096)
    близко("Честная частичная информация", .45-.1-.08, .27)
    близко("Ложь при сильной норме", .8-.1-.08-сопротивление(.8, .9, .8), .044)
    близко("Ложь при слабой норме", .8-.1-.08-сопротивление(.1, .9, .8), .548)
    проверить("Изменение нормы меняет предпочтение", .044 < .27 < .548)
    близко("Медленная переоценка нормы", принятие_нормы(.8, .2, .5, 1, 1), .7940299002495008)
    близко("Без принятого нового основания норма не меняется", принятие_нормы(.8, .2, .5, 0, 1), .8)
    близко("Вклад затратной помощи", .6*.7-.25, .17)
    скорость = скорость_признаков(.8, .5, .5)
    близко("Скорость получения признаков", скорость, 1.25)
    близко("Время грубого признака", 1/скорость, .8)
    близко("Время подробного признака", 3/скорость, 2.4)
    близко("Сон отключает сознательное получение", скорость_признаков(.8, .5, .5, False), 0)
    близко("Нет чувственного доступа", скорость_признаков(.8, .5, .5, True, False), 0)
    близко("Время полного нейтрального бюджета", (4+math.floor(28*.5))/(2+6*.5), 3.6)
    отклонено = False
    try:
        сопротивление(1.1, .8, .7)
    except ValueError:
        отклонено = True
    проверить("Недопустимый диапазон отклоняется", отклонено)
    отклонено = False
    try:
        надёжность(1, 0, сила=0)
    except ValueError:
        отклонено = True
    проверить("Нулевая сила исходного ожидания отклоняется", отклонено)
    случай = random.Random(1701)
    for _ in range(2000):
        а, п, к, д, с, р = [случай.random() for _ in range(6)]
        if not 0 <= забота(а, п, к, д, с, р) <= 1:
            raise AssertionError("Диапазон заботы")
        if not 0 <= принятие_нормы(а, с, п, к, д) <= 1:
            raise AssertionError("Диапазон принятия")
        if not 0 <= сопротивление(а, п, к, д) <= 1:
            raise AssertionError("Диапазон сопротивления")
        if сопротивление(а, п, к) > сопротивление(1, п, к) + 1e-15:
            raise AssertionError("Монотонность сопротивления")
    проверить("2000 наборов: границы и монотонность", True)
    return выполнено


if __name__ == "__main__":
    результат = проверки()
    for номер, имя in enumerate(результат, 1):
        print(f"{номер:02}: OK — {имя}")
    print(f"Итого: {len(результат)} проверок. Только формулы, не ядро игры.")
